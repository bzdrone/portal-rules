// Generates src/generated/sdk.ts from the Portal SDK's mod type declarations.
// Usage: node scripts/gen-sdk.mjs [sdkPath]
import { readFileSync, writeFileSync } from "node:fs";
const sdk = process.argv[2] ?? process.env.PORTAL_SDK ?? "C:/PortalSDK";
const src = readFileSync(`${sdk}/code/types/mod/index.d.ts`, "utf8");
const version = JSON.parse(readFileSync(`${sdk}/sdk.version.json`, "utf8")).version;

const functions = new Set();
const enums = new Set();
for (const m of src.matchAll(/^    export function (\w+)\(/gm)) functions.add(m[1]);
for (const m of src.matchAll(/^    export enum (\w+)/gm)) enums.add(m[1]);

// namespace EventHandlerSignatures { export function OnX(a: mod.T, ...): void; }
const events = {};
const ns = src.slice(src.indexOf("namespace EventHandlerSignatures"));
for (const m of ns.matchAll(/export function (On\w+|Ongoing\w+)\(([^)]*)\)\s*:\s*void/g)) {
  const params = m[2].split(",").map((p) => p.trim()).filter(Boolean).map((p) => {
    const [name, type] = p.split(":").map((s) => s.trim());
    return { name, type: type.replace(/^mod\./, "") };
  });
  events[m[1]] = params;
}

const out = `// Generated by scripts/gen-sdk.mjs from Portal SDK ${version}. Do not edit.
export const SDK_VERSION = ${JSON.stringify(version)};

export interface EventParam { name: string; type: string }

/** Event handler signatures (name -> params). */
export const EVENTS: Record<string, EventParam[]> = ${JSON.stringify(events, null, 2)};

/** Names of \`mod.*\` functions. */
export const MOD_FUNCTIONS: ReadonlySet<string> = new Set(${JSON.stringify([...functions].sort())});

/** Names of \`mod.*\` enums. */
export const MOD_ENUMS: ReadonlySet<string> = new Set(${JSON.stringify([...enums].sort())});
`;
writeFileSync("src/generated/sdk.ts", out);
console.log(`events ${Object.keys(events).length}, functions ${functions.size}, enums ${enums.size}`);
